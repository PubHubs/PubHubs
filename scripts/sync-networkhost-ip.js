#!/usr/bin/env node
/**
 * Keeps `ios/App/App/Info.plist`'s ATS exception domain, and `global-client/public/client-config.local.js`'s
 * PUBHUBS_URL/PHC_URL overrides, in sync with the `networkhost.ip`. PubHubs Central hands out hub/MSS URLs
 * built from that alias (not `localhost`), as configured in `pubhubs/pubhubs.toml` (`pubhubs/pubhubs.default.toml`
 * is used as a fallback if `pubhubs.toml` doesn't exist yet).
 *
 * Both matter for real-device testing: `localhost` resolves to the dev machine in the Simulator (shared
 * network), but resolves to the device itself on a real device, where nothing is listening — so
 * client-config.local.js needs to point at the dev machine's LAN IP, and Info.plist's ATS needs to allow it.
 *
 * client-config.local.js is gitignored and generated fresh each run (loaded after the tracked
 * client-config.js in global-client/index.html, so it can override individual _env keys) — the tracked
 * client-config.js itself is never touched, only read (to pick up its PUBHUBS_URL/PHC_URL ports).
 *
 * This script never needs to be run by hand, since it's wired into `npm run cap:sync` / `cap:run:ios` / `cap:open:ios` (see package.json).
 *
 * See docs/app/README.md and pubhubs/src/servers/config/host_aliases.rs for background.
 */

import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT, resolveNetworkhostIp } from './lib/resolve-networkhost-ip.js';

const INFO_PLIST = path.join(REPO_ROOT, 'ios', 'App', 'App', 'Info.plist');
const CLIENT_CONFIG = path.join(REPO_ROOT, 'global-client', 'public', 'client-config.js');
const CLIENT_CONFIG_LOCAL = path.join(REPO_ROOT, 'global-client', 'public', 'client-config.local.js');

const IPV4_KEY_RE = /<key>(\d{1,3}(?:\.\d{1,3}){3})<\/key>/g;
const LOCALHOST_URL_RE = /(\w+):\s*'http:\/\/localhost:(\d+)'/g;

function syncInfoPlist(ip) {
	const plist = fs.readFileSync(INFO_PLIST, 'utf8');
	const matches = [...plist.matchAll(IPV4_KEY_RE)];

	if (matches.length !== 1) {
		console.error(`sync-networkhost-ip: expected exactly one IPv4 <key> entry in ${path.relative(REPO_ROOT, INFO_PLIST)}'s NSExceptionDomains, found ${matches.length}.`);
		console.error('The plist structure may have changed — please update it by hand instead of guessing. See docs/app/README.md.');
		process.exitCode = 1;
		return;
	}

	const currentIp = matches[0][1];
	if (currentIp === ip) {
		console.log(`sync-networkhost-ip: already in sync (${ip}).`);
		return;
	}

	const updated = plist.replace(`<key>${currentIp}</key>`, `<key>${ip}</key>`);
	fs.writeFileSync(INFO_PLIST, updated);
	console.log(`sync-networkhost-ip: updated Info.plist ATS exception ${currentIp} → ${ip}`);
}

function syncClientConfig(ip) {
	const config = fs.readFileSync(CLIENT_CONFIG, 'utf8');
	const keyPorts = [...config.matchAll(LOCALHOST_URL_RE)].map(([, key, port]) => ({ key, port }));

	if (keyPorts.length === 0) {
		console.error(`sync-networkhost-ip: found no '<KEY>: 'http://localhost:<port>'' entries in ${path.relative(REPO_ROOT, CLIENT_CONFIG)}.`);
		console.error('The file structure may have changed — please update it by hand instead of guessing. See docs/app/README.md.');
		process.exitCode = 1;
		return;
	}

	const generated = keyPorts.map(({ key, port }) => `_env.${key} = 'http://${ip}:${port}';\n`).join('');
	const header = '// Auto-generated by `npm run sync:networkhost-ip` — see scripts/sync-networkhost-ip.js. Do not edit by hand.\n';
	const updated = header + generated;

	if (fs.existsSync(CLIENT_CONFIG_LOCAL) && fs.readFileSync(CLIENT_CONFIG_LOCAL, 'utf8') === updated) {
		console.log(`sync-networkhost-ip: client-config.local.js already in sync (${ip}).`);
		return;
	}

	fs.writeFileSync(CLIENT_CONFIG_LOCAL, updated);
	console.log(`sync-networkhost-ip: updated client-config.local.js to use ${ip}`);
}

async function main() {
	let ip;
	try {
		ip = await resolveNetworkhostIp();
	} catch (err) {
		console.warn(`sync-networkhost-ip: could not auto-detect networkhost IP (${err.message}) — leaving Info.plist and client-config.local.js unchanged.`);
		console.warn('Set an explicit networkhost.ip in pubhubs/pubhubs.toml if this keeps happening.');
		return;
	}

	if (!ip) {
		console.warn('sync-networkhost-ip: neither networkhost.ip nor networkhost.source_ip_for set in pubhubs/pubhubs.toml (or pubhubs.default.toml) — leaving Info.plist and client-config.local.js unchanged.');
		return;
	}

	syncInfoPlist(ip);
	syncClientConfig(ip);
}

main();
