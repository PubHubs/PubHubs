#!/usr/bin/env node
/**
 * Generates the locally-trusted TLS cert (via `mkcert`) and Caddyfile used by `mask run proxy` to front the hub-client and the Matrix/Synapse API with HTTPS on the `networkhost` IP.
 * See docs/app/README.md.
 *
 * These are NEW ports (existing plain-port + PORT_OFFSET), not a replacement — PHC and yivi still talk to each hub over the plain-HTTP `networkhost` ports from pubhubs.toml.
 * This only adds a parallel HTTPS frontend for browser/app clients; global-client and PHC don't need it (see docs/app/README.md).
 *
 * Regenerated on every `mask run proxy` invocation, so it always matches the current network. Requires `mkcert` and `caddy` on PATH (both provided by the Nix devshell).
 */

import { REPO_ROOT, resolveNetworkhostIp } from './lib/resolve-networkhost-ip.js';

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const CERTS_DIR = path.join(REPO_ROOT, 'certs');
const CERT_FILE = path.join(CERTS_DIR, 'dev-proxy-cert.pem');
const KEY_FILE = path.join(CERTS_DIR, 'dev-proxy-key.pem');
const GENERATED_FOR_IP_FILE = path.join(CERTS_DIR, '.generated-for-ip');
const CADDYFILE = path.join(REPO_ROOT, 'Caddyfile.local');

const NUM_TESTHUBS = 5; // testhub0..testhub4, see pubhubs_hub/start_testhub.py
const PORT_OFFSET = 10000; // HTTPS frontend port = plain backend port + this offset

// Plain-HTTP backend port bases that get an HTTPS frontend, one per testhub instance (n = 0..NUM_TESTHUBS-1).
const FRONTED_PORT_BASES = [
	8001, // hub-client's own Vite dev server (hub_client_url — the iframe src)
	8008, // Matrix/Synapse API (hub-client's HUB_URL)
];

function ensureMkcert() {
	try {
		execFileSync('mkcert', ['-CAROOT'], { stdio: 'pipe' });
	} catch (err) {
		throw new Error(`'mkcert' is not installed or not on PATH (needed for locally-trusted dev HTTPS — see docs/app/README.md): ${err.message}`);
	}
}

function ensureCaddyOnPath() {
	try {
		execFileSync('caddy', ['version'], { stdio: 'pipe' });
	} catch (err) {
		throw new Error(`'caddy' is not installed or not on PATH (needed to run the dev HTTPS proxy — see docs/app/README.md): ${err.message}`);
	}
}

function ensureCert(ip) {
	fs.mkdirSync(CERTS_DIR, { recursive: true });

	// mkcert bakes the SAN list in at generation time, so we track which IP the current cert covers via
	// a sibling marker file rather than re-parsing the cert.
	const generatedForIp = fs.existsSync(GENERATED_FOR_IP_FILE) ? fs.readFileSync(GENERATED_FOR_IP_FILE, 'utf8').trim() : null;

	if (generatedForIp === ip && fs.existsSync(CERT_FILE) && fs.existsSync(KEY_FILE)) {
		console.log(`gen-dev-proxy: cert already up to date for ${ip}.`);
		return;
	}

	console.log(`gen-dev-proxy: generating dev HTTPS cert for ${ip} (and localhost/127.0.0.1)...`);
	execFileSync('mkcert', ['-cert-file', CERT_FILE, '-key-file', KEY_FILE, ip, 'localhost', '127.0.0.1'], { stdio: 'inherit' });
	fs.writeFileSync(GENERATED_FOR_IP_FILE, ip);
}

function writeCaddyfile(ip) {
	let blocks = '';
	for (const base of FRONTED_PORT_BASES) {
		for (let n = 0; n < NUM_TESTHUBS; n++) {
			const plainPort = base + n;
			const httpsPort = plainPort + PORT_OFFSET;
			blocks += `:${httpsPort} {\n\ttls ${CERT_FILE} ${KEY_FILE}\n\treverse_proxy 127.0.0.1:${plainPort}\n}\n\n`;
		}
	}

	const header = '# Auto-generated by scripts/gen-dev-proxy.js (via `mask run proxy`) — see docs/app/README.md. Do not edit by hand.\n' + `# Fronting IP: ${ip}\n\n`;

	fs.writeFileSync(CADDYFILE, (header + blocks).trimEnd() + '\n');
	console.log(`gen-dev-proxy: wrote ${path.relative(REPO_ROOT, CADDYFILE)} (${FRONTED_PORT_BASES.length} services x ${NUM_TESTHUBS} testhubs).`);
}

async function main() {
	try {
		ensureMkcert();
		ensureCaddyOnPath();
	} catch (err) {
		console.error(`gen-dev-proxy: ${err.message}`);
		process.exitCode = 1;
		return;
	}

	let ip;
	try {
		ip = await resolveNetworkhostIp();
	} catch (err) {
		console.error(`gen-dev-proxy: could not auto-detect networkhost IP (${err.message}).`);
		console.error('Set an explicit networkhost.ip in pubhubs/pubhubs.toml if this keeps happening.');
		process.exitCode = 1;
		return;
	}

	if (!ip) {
		console.error('gen-dev-proxy: neither networkhost.ip nor networkhost.source_ip_for set in pubhubs/pubhubs.toml (or pubhubs.default.toml) — cannot generate the dev HTTPS proxy config.');
		process.exitCode = 1;
		return;
	}

	ensureCert(ip);
	writeCaddyfile(ip);
}

main();
